/**
 * @file connection_client_config_test.c
 * @brief Checks, when compiled, how az_iot_connection_client_config.h resolves the default
 * limits. One case per build: AZ_IOT_CONNECTION_CLIENT_CONFIG_TEST_<case>.
 */

// Each case sets its own inputs: drop any from the build (e.g. CMake options).
#undef AZ_IOT_CONNECTION_CLIENT_CONFIG_FILE
#undef AZ_IOT_CONNECTION_CLIENT_DEFAULT_MAX_PENDING_PUBLISHES
#undef AZ_IOT_CONNECTION_CLIENT_DEFAULT_MAX_PUBLISH_RESERVATIONS
#undef AZ_IOT_CONNECTION_CLIENT_DEFAULT_MAX_PERSISTENT_SUBSCRIPTIONS
#undef AZ_IOT_CONNECTION_CLIENT_DEFAULT_MAX_FEATURE_OBSERVERS
#undef AZ_IOT_CONNECTION_CLIENT_DEFAULT_MAX_APPLICATION_STATE_OBSERVERS
#undef AZ_IOT_CONNECTION_CLIENT_DEFAULT_MAX_FEATURE_CLIENTS
#undef AZ_IOT_CONNECTION_CLIENT_DEFAULT_MAX_INBOUND_HANDLERS

#if defined(AZ_IOT_CONNECTION_CLIENT_CONFIG_TEST_DEFAULT)
#define EXPECTED_PENDING_PUBLISHES 16
#define EXPECTED_APPLICATION_STATE_OBSERVERS 4
#define EXPECTED_INBOUND_HANDLERS 8
#elif defined(AZ_IOT_CONNECTION_CLIENT_CONFIG_TEST_OVERRIDE)
#define AZ_IOT_CONNECTION_CLIENT_DEFAULT_MAX_PENDING_PUBLISHES 4
#define EXPECTED_PENDING_PUBLISHES 4
#define EXPECTED_APPLICATION_STATE_OBSERVERS 4
#define EXPECTED_INBOUND_HANDLERS 8
#elif defined(AZ_IOT_CONNECTION_CLIENT_CONFIG_TEST_CONFIG_FILE)
// The file sets PENDING_PUBLISHES; a definition here adds another.
#define AZ_IOT_CONNECTION_CLIENT_CONFIG_FILE "connection_client_config_test_user.h"
#define AZ_IOT_CONNECTION_CLIENT_DEFAULT_MAX_APPLICATION_STATE_OBSERVERS 1
#define EXPECTED_PENDING_PUBLISHES 32
#define EXPECTED_APPLICATION_STATE_OBSERVERS 1
#define EXPECTED_INBOUND_HANDLERS 8
#else
#error "Define AZ_IOT_CONNECTION_CLIENT_CONFIG_TEST_<case>"
#endif

#include "azure/iot/az_iot_connection_client.h"

#if AZ_IOT_CONNECTION_CLIENT_DEFAULT_MAX_PENDING_PUBLISHES != EXPECTED_PENDING_PUBLISHES
#error "AZ_IOT_CONNECTION_CLIENT_DEFAULT_MAX_PENDING_PUBLISHES"
#endif
#if AZ_IOT_CONNECTION_CLIENT_DEFAULT_MAX_APPLICATION_STATE_OBSERVERS \
    != EXPECTED_APPLICATION_STATE_OBSERVERS
#error "AZ_IOT_CONNECTION_CLIENT_DEFAULT_MAX_APPLICATION_STATE_OBSERVERS"
#endif
#if AZ_IOT_CONNECTION_CLIENT_DEFAULT_MAX_INBOUND_HANDLERS != EXPECTED_INBOUND_HANDLERS
#error "AZ_IOT_CONNECTION_CLIENT_DEFAULT_MAX_INBOUND_HANDLERS"
#endif

/* The static size follows the defaults; the client's own layout does not. */
typedef char default_workspace_size_follows_the_defaults
    [AZ_IOT_CONNECTION_CLIENT_DEFAULT_WORKSPACE_SIZE
             == AZ_IOT_CONNECTION_CLIENT_WORKSPACE_SIZE(
                 EXPECTED_PENDING_PUBLISHES,
                 2,
                 8,
                 10,
                 EXPECTED_APPLICATION_STATE_OBSERVERS,
                 8,
                 EXPECTED_INBOUND_HANDLERS)
         ? 1
         : -1];

int main(void) { return 0; }
